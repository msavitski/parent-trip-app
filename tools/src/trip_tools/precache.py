"""`trip precache`: write the app's file list and version into web/sw.js.

The service worker caches exactly these files as one snapshot named after VERSION, a hash of their
contents. Any change to a file in web/ therefore changes sw.js, and phones download the new
snapshot in the background. trip.enc is left out on purpose: it is data with its own cache, so a
trip update never changes sw.js. So is vendor/ (pdf.js, only admin mode uses it): the worker caches those
files the first time they're used, so the family's phones never download them.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

START = "// <precache> generated by `trip precache`: do not edit by hand"
END = "// </precache>"
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
SKIP = {"sw.js", "trip.enc"}
LAZY = "vendor/"  # cached on first use, see web/sw.js


class PrecacheError(Exception):
    pass


def app_files(web: Path) -> list[str]:
    """Every file of the site except sw.js, trip.enc and vendor/, as paths relative to web/."""
    files = []
    for file in sorted(web.rglob("*")):
        rel = file.relative_to(web).as_posix()
        hidden = any(part.startswith(".") for part in file.parts)
        if file.is_file() and rel not in SKIP and not rel.startswith(LAZY) and not hidden:
            files.append(rel)
    return files


def version(web: Path, files: list[str]) -> str:
    """Hash of names and contents. Line endings are normalised, so Windows and Linux agree."""
    digest = hashlib.sha256()
    for rel in files:
        digest.update(rel.encode() + b"\0")
        digest.update((web / rel).read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return digest.hexdigest()[:12]


def block(web: Path) -> str:
    files = app_files(web)
    lines = [START, f"const VERSION = '{version(web, files)}';", "const APP_FILES = ["]
    lines += [f"  '{f}'," for f in ["./", *files]]
    lines += ["];", END]
    return "\n".join(lines)


def update(service_worker: Path, web: Path, write: bool = True) -> bool:
    """Returns whether sw.js was (or, with write=False, would be) changed."""
    source = service_worker.read_text(encoding="utf-8")
    if not BLOCK.search(source):
        raise PrecacheError(f"{service_worker} has no precache block ({START} … {END}).")
    new_source = BLOCK.sub(lambda _: block(web), source)
    changed = new_source != source.replace("\r\n", "\n")
    if changed and write:
        service_worker.write_text(new_source, encoding="utf-8", newline="\n")
    return changed
