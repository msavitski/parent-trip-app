/**
 * Safe HTML templates and the icon set.
 *
 *   html`<p class="note">${text}</p>`
 *
 * Every interpolated value is escaped, unless it is itself the result of html`` or icon().
 * Arrays are joined, and null/undefined render as nothing. Other values (including 0 and false)
 * render as text, because attributes like data-arg="0" and aria-pressed="false" depend on it.
 * Use `cond ? html`…` : ''`, not `cond && html`…``, or a false condition prints "false".
 */

/** Markup that is already safe to insert. */
export class Html {
  /** @param {string} markup */
  constructor(markup) {
    this.markup = markup;
  }

  toString() {
    return this.markup;
  }
}

/** @typedef {Html | string | number | boolean | null | undefined | Value[]} Value */

/** @type {Record<string, string>} */
const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/**
 * @param {Value} value
 * @returns {string}
 */
function part(value) {
  if (value == null) return '';
  if (value instanceof Html) return value.markup;
  if (Array.isArray(value)) return value.map(part).join('');
  return String(value).replace(/[&<>"']/g, (c) => ESCAPES[c]);
}

/**
 * @param {TemplateStringsArray} strings
 * @param {...Value} values
 * @returns {Html}
 */
export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += part(values[i]) + strings[i + 1];
  return new Html(out);
}

/**
 * Replace an element's content.
 * @param {Element} element
 * @param {Html} content
 */
export function mount(element, content) {
  element.innerHTML = content.markup;
}

